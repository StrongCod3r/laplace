const iconNodesByName = Object.fromEntries(
  Object.entries(lucideNodes).map(([name, node]) => [
    name
      .replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`)
      .replace(/^-/, '')
      .replace(/([a-z])(\d)/g, '$1-$2'),
    node,
  ]),
);

export function iconMarkup(name: string, size: string | number = '1em', className = '') {
  const iconName = String(name || 'file');
  const node = iconNodesByName[iconName] || iconNodesByName['circle-help'];
  const classes = [`lucide lucide-${iconName} app-lucide`, className].filter(Boolean).join(' ');
  return createElement(node, {
    width: size,
    height: size,
    class: classes,
    'aria-hidden': 'true',
    focusable: 'false',
  }).outerHTML;
}

export function hydrateStaticIcons(root = document) {
  createIcons({ icons: lucideNodes, attrs: { class: 'app-lucide', 'stroke-width': 2 }, root });
}
